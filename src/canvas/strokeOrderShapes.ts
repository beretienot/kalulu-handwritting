// (src/pages/StrokeOrderPage.tsx vía strokeOrderPath.ts).
//
// A propósito NO se reusa letterShapes.ts: ese archivo también alimenta el puntaje $P
// de TracingCanvas (ver textTemplate.ts), que es invariante a orden/dirección de trazo.
// Acá el orden y la dirección SÍ importan (se enseña cómo se escribe, no solo qué forma
// queda) — la cantidad de trazos, su orden, su dirección y la forma exacta de cada curva
// vienen de calcar (extracción automática por procesamiento de imagen, punto por punto)
// la guía de líneas punteadas del material de referencia pedagógico de Kalulu, no de una
// aproximación a mano. Los trazos rectos (astas, renglones) sí se dejaron a mano: ahí no
// hay ambigüedad de forma y el punteado de la referencia no agrega precisión.
//
// Las curvas con muchos puntos de control (calcadas de la referencia) evitan el
// "overshoot" de Catmull-Rom (ver smoothCurve en strokeOrderPath.ts) que aparecía con
// las aproximaciones viejas de pocos puntos: al haber poco cambio de dirección por
// segmento, la curva no se dispara fuera de la letra.
//
// Excepción: en d/g/n la tipografía real (Mulish) tiene proporciones bastante distintas
// a la de la hoja de referencia justo donde el asta/pierna se junta con la panza/arco —
// calcar el punteado ahí llevaba el trazo lejos de la tinta real y snapPointsToInkCenter
// no llegaba a corregirlo (queda fuera de su radio de búsqueda). Para esos tres casos se
// usa una elipse genérica (`arc`/`bowl`) en vez del calco, que sí cae cerca de cualquier
// variante razonable de la letra.

import type { Stroke } from "./pointCloudRecognizer";

function arc(cx: number, cy: number, rx: number, ry: number, startDeg: number, endDeg: number, steps = 16): Stroke {
  const points: Stroke = [];
  for (let i = 0; i <= steps; i++) {
    const deg = startDeg + ((endDeg - startDeg) * i) / steps;
    const rad = (deg * Math.PI) / 180;
    points.push({ x: cx + rx * Math.cos(rad), y: cy + ry * Math.sin(rad) });
  }
  return points;
}

// Panza tipo "d/g": arranca cerca de las 2 en punto y da toda la vuelta en sentido
// antihorario (ángulo decreciente), como se escribe a mano.
function bowl(cx: number, cy: number, rx: number, ry: number, startDeg = -20): Stroke {
  return arc(cx, cy, rx, ry, startDeg, startDeg - 360);
}

