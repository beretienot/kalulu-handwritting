// Las vocales con tilde reutilizan la forma de la vocal base, con un trazo extra
// (la tilde) arriba a la derecha del cuerpo de la letra.
const ACCENT_TO_BASE: Record<string, string> = {
  Á: "A", É: "E", Í: "I", Ó: "O", Ú: "U",
  á: "a", é: "e", í: "i", ó: "o", ú: "u",
};

// De abajo (más cerca de la letra) hacia arriba: así se escribe a mano un acento agudo
// (un tilde rápido hacia arriba-derecha), y así se ve realmente dibujado en la fuente
// (sube de izquierda a derecha, como "/"). computePathFit (strokeOrderPath.ts) calcula
// el encuadre recorriendo los puntos reales de cada trazo, así que no hace falta
// reservarle espacio a mano: al subir a y negativo, ya queda incluida en el bounding box.
const ACCENT_TICK: Stroke = [{ x: 0.35, y: -0.05 }, { x: 0.6, y: -0.28 }];

export function getStrokeOrderShape(char: string): Stroke[] | null {
  if (LETTER_SHAPES[char]) return LETTER_SHAPES[char];
  const base = ACCENT_TO_BASE[char];
  if (base && LETTER_SHAPES[base]) return [...LETTER_SHAPES[base], ACCENT_TICK];
  return null;
}
